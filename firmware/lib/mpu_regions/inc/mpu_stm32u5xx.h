/*
 * STM32U5 peripheral address map (non-secure):
 *   APB1  0x40000000 - 0x4000FFFF  (IWDG, USART2/3, I2C1/2, etc.)
 *   APB2  0x40010000 - 0x4001FFFF  (USART1, SPI1, etc.)
 *   AHB1  0x40020000 - 0x4002FFFF  (GPDMA1, FLASH ctrl, CRC)
 *   AHB2  0x42020000 - 0x420D1FFF  (GPIO A-I, ADC1, OCTOSPI1 ctrl)
 *   APB3  0x46000000 - 0x4600FFFF  (SYSCFG, LPUART1, etc.)
 *   AHB3  0x46020000 - 0x46023FFF  (RCC, PWR, EXTI)
 *
 * FreeRTOS leaves 3 user MPU regions per task. Most tasks need at
 * least one region slot for data, so at most one or two slots remain
 * for peripherals. Ranges below are chosen to cover only the buses
 * that each task actually touches rather than the full 512 MB span.
 */

/* Full peripheral span (0x40000000–0x5FFFFFFF) – avoid where possible. */
#define MPU_PERIPHERAL_BASE_ADDR  ((void*)0x40000000)
#define MPU_PERIPHERAL_TOTAL_SIZE 0x20000000

