package build.wallet.nfc.platform

import uniffi.actionproof.Action

/**
 * KMP-native enum representing privileged action types for action proofs.
 * Maps 1:1 with [Action] but exports cleanly to iOS Swift.
 */
enum class ActionProofAction {
  SET_SPEND_WITHOUT_HARDWARE,
  DISABLE_SPEND_WITHOUT_HARDWARE,
  SET_VERIFICATION_THRESHOLD,
  SET_RECOVERY_EMAIL,
  DISABLE_RECOVERY_EMAIL,
  SET_RECOVERY_PHONE,
  DISABLE_RECOVERY_PHONE,
  SET_RECOVERY_PUSH_NOTIFICATIONS,
  DISABLE_RECOVERY_PUSH_NOTIFICATIONS,
  ADD_RECOVERY_CONTACT,
  REMOVE_RECOVERY_CONTACT,
  REMOVE_RECOVERY_CUSTOMER,
  ADD_BENEFICIARY,
  REMOVE_BENEFICIARY,
  REMOVE_BENEFACTOR,
  CREATE_LOST_APP_RECOVERY,
  CREATE_LOST_HARDWARE_RECOVERY,
  CREATE_SPENDING_KEYSET,
  ROTATE_SPENDING_KEYSET,
  DELETE_ACCOUNT,
  UPDATE_DESCRIPTOR_BACKUPS,
  CANCEL_LOST_APP_RECOVERY,
  CANCEL_LOST_HARDWARE_RECOVERY,
  CANCEL_CONFLICTING_RECOVERY,
  SEND_RECOVERY_VERIFICATION_CODE,
  VERIFY_RECOVERY_VERIFICATION_CODE,
  ROTATE_APP_AUTH_KEYS,
  ;

  /** Converts to the canonical PascalCase string for the firmware protocol. */
  fun toPascalCase(): String =
    when (this) {
      SET_SPEND_WITHOUT_HARDWARE -> "SetSpendWithoutHardware"
      DISABLE_SPEND_WITHOUT_HARDWARE -> "DisableSpendWithoutHardware"
      SET_VERIFICATION_THRESHOLD -> "SetVerificationThreshold"
      SET_RECOVERY_EMAIL -> "SetRecoveryEmail"
      DISABLE_RECOVERY_EMAIL -> "DisableRecoveryEmail"
      SET_RECOVERY_PHONE -> "SetRecoveryPhone"
      DISABLE_RECOVERY_PHONE -> "DisableRecoveryPhone"
      SET_RECOVERY_PUSH_NOTIFICATIONS -> "SetRecoveryPushNotifications"
      DISABLE_RECOVERY_PUSH_NOTIFICATIONS -> "DisableRecoveryPushNotifications"
      ADD_RECOVERY_CONTACT -> "AddRecoveryContact"
      REMOVE_RECOVERY_CONTACT -> "RemoveRecoveryContact"
      REMOVE_RECOVERY_CUSTOMER -> "RemoveRecoveryCustomer"
      ADD_BENEFICIARY -> "AddBeneficiary"
      REMOVE_BENEFICIARY -> "RemoveBeneficiary"
      REMOVE_BENEFACTOR -> "RemoveBenefactor"
      CREATE_LOST_APP_RECOVERY -> "CreateLostAppRecovery"
      CREATE_LOST_HARDWARE_RECOVERY -> "CreateLostHardwareRecovery"
      CREATE_SPENDING_KEYSET -> "CreateSpendingKeyset"
      ROTATE_SPENDING_KEYSET -> "RotateSpendingKeyset"
      DELETE_ACCOUNT -> "DeleteAccount"
      UPDATE_DESCRIPTOR_BACKUPS -> "UpdateDescriptorBackups"
      CANCEL_LOST_APP_RECOVERY -> "CancelLostAppRecovery"
      CANCEL_LOST_HARDWARE_RECOVERY -> "CancelLostHardwareRecovery"
      CANCEL_CONFLICTING_RECOVERY -> "CancelConflictingRecovery"
      SEND_RECOVERY_VERIFICATION_CODE -> "SendRecoveryVerificationCode"
      VERIFY_RECOVERY_VERIFICATION_CODE -> "VerifyRecoveryVerificationCode"
      ROTATE_APP_AUTH_KEYS -> "RotateAppAuthKeys"
    }

  companion object {
    /** Converts from the UniFFI [Action] enum to the KMP enum. */
    fun from(action: Action): ActionProofAction =
      when (action) {
        Action.SET_SPEND_WITHOUT_HARDWARE -> SET_SPEND_WITHOUT_HARDWARE
        Action.DISABLE_SPEND_WITHOUT_HARDWARE -> DISABLE_SPEND_WITHOUT_HARDWARE
        Action.SET_VERIFICATION_THRESHOLD -> SET_VERIFICATION_THRESHOLD
        Action.SET_RECOVERY_EMAIL -> SET_RECOVERY_EMAIL
        Action.DISABLE_RECOVERY_EMAIL -> DISABLE_RECOVERY_EMAIL
        Action.SET_RECOVERY_PHONE -> SET_RECOVERY_PHONE
        Action.DISABLE_RECOVERY_PHONE -> DISABLE_RECOVERY_PHONE
        Action.SET_RECOVERY_PUSH_NOTIFICATIONS -> SET_RECOVERY_PUSH_NOTIFICATIONS
        Action.DISABLE_RECOVERY_PUSH_NOTIFICATIONS -> DISABLE_RECOVERY_PUSH_NOTIFICATIONS
        Action.ADD_RECOVERY_CONTACT -> ADD_RECOVERY_CONTACT
        Action.REMOVE_RECOVERY_CONTACT -> REMOVE_RECOVERY_CONTACT
        Action.REMOVE_RECOVERY_CUSTOMER -> REMOVE_RECOVERY_CUSTOMER
        Action.ADD_BENEFICIARY -> ADD_BENEFICIARY
        Action.REMOVE_BENEFICIARY -> REMOVE_BENEFICIARY
        Action.REMOVE_BENEFACTOR -> REMOVE_BENEFACTOR
        Action.CREATE_LOST_APP_RECOVERY -> CREATE_LOST_APP_RECOVERY
        Action.CREATE_LOST_HARDWARE_RECOVERY -> CREATE_LOST_HARDWARE_RECOVERY
        Action.CREATE_SPENDING_KEYSET -> CREATE_SPENDING_KEYSET
        Action.ROTATE_SPENDING_KEYSET -> ROTATE_SPENDING_KEYSET
        Action.DELETE_ACCOUNT -> DELETE_ACCOUNT
        Action.UPDATE_DESCRIPTOR_BACKUPS -> UPDATE_DESCRIPTOR_BACKUPS
        Action.CANCEL_LOST_APP_RECOVERY -> CANCEL_LOST_APP_RECOVERY
        Action.CANCEL_LOST_HARDWARE_RECOVERY -> CANCEL_LOST_HARDWARE_RECOVERY
        Action.CANCEL_CONFLICTING_RECOVERY -> CANCEL_CONFLICTING_RECOVERY
        Action.SEND_RECOVERY_VERIFICATION_CODE -> SEND_RECOVERY_VERIFICATION_CODE
        Action.VERIFY_RECOVERY_VERIFICATION_CODE -> VERIFY_RECOVERY_VERIFICATION_CODE
        Action.ROTATE_APP_AUTH_KEYS -> ROTATE_APP_AUTH_KEYS
      }
  }
}
